CREATE TABLE COLHEITA_CANA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TALHAO VARCHAR2(30) NOT NULL,
    AREA_HECTARES NUMBER(10, 2) NOT NULL,
    PRODUTIVIDADE_ESTIMADA NUMBER(10, 2) NOT NULL,
    PRODUCAO_COLHIDA NUMBER(10, 2) NOT NULL,
    VALOR_TONELADA NUMBER(10, 2) NOT NULL,
    PRODUCAO_ESPERADA NUMBER(10, 2) NOT NULL,
    PERDA_TONELADAS NUMBER(10, 2) NOT NULL,
    PERCENTUAL_PERDA NUMBER(6, 2) NOT NULL,
    PREJUIZO_ESTIMADO NUMBER(12, 2) NOT NULL,
    STATUS_PERDA VARCHAR2(15) NOT NULL,
    DATA_REGISTRO VARCHAR2(20) NOT NULL
);